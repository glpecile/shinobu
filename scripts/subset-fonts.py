"""Subsets the app's fonts and writes the results this repo commits.

    uv run scripts/subset-fonts.py

Rerun after bumping @expo-google-fonts/* or @react-native-vector-icons/ionicons,
adding an Ionicons name, loading another weight, turning on an OpenType feature
(`tabular-nums` is `tnum`). `bun test` fails on a missing icon.

Each font keeps every character it had, because titles, names and bios come
from provider APIs, and loses unused features and hinting. Web gets one woff2
per family, not a core plus a `unicode-range` extended file: kerning only
applies within one file, and Inter kerns punctuation against Greek and Cyrillic
(docs/solutions/font-subset-split-changes-kerning.md).
"""

import json
import re
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
NODE = ROOT / "node_modules"
NATIVE_OUT = ROOT / "src/assets/fonts"
WEB_OUT = ROOT / "public/fonts"
WEB_FACES = ROOT / "src/lib/fonts/web-faces.ts"
ICON_NAMES = ROOT / "src/lib/fonts/ionicons-subset.json"

# Features browsers and native text stacks apply without being asked. HarfBuzz
# turns numr/dnom on around U+2044 by itself.
DEFAULT_FEATURES = ["ccmp", "locl", "rvrn", "rlig", "liga", "clig", "calt", "kern", "mark", "mkmk", "numr", "dnom"]

# family (the fontFamily the app uses) -> (source, output stem, extra features)
FONTS = {
    "SpaceGrotesk_700Bold": ("@expo-google-fonts/space-grotesk/700Bold/SpaceGrotesk_700Bold.ttf", "space-grotesk-700", []),
    # list-progress.tsx: `font-sans tabular-nums`.
    "Inter_400Regular": ("@expo-google-fonts/inter/400Regular/Inter_400Regular.ttf", "inter-400", ["tnum"]),
    "Inter_400Regular_Italic": ("@expo-google-fonts/inter/400Regular_Italic/Inter_400Regular_Italic.ttf", "inter-400-italic", []),
    "Inter_600SemiBold": ("@expo-google-fonts/inter/600SemiBold/Inter_600SemiBold.ttf", "inter-600", []),
}
IONICONS = "@react-native-vector-icons/ionicons"


def options(features, flavor=None):
    opts = subset.Options()
    opts.layout_features = features
    opts.hinting = False
    opts.drop_tables += ["FFTM"]
    # Copyright, names, and the OFL notice the license asks to travel with the font.
    opts.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    opts.flavor = flavor
    return opts


def write(source, unicodes, features, path, license_text, flavor=None):
    font = TTFont(source, recalcTimestamp=False)
    subsetter = subset.Subsetter(options(features, flavor))
    subsetter.populate(unicodes=unicodes)
    subsetter.subset(font)
    # Each redistributed binary carries its full license, including web assets.
    font["name"].setName(license_text, 13, 3, 1, 0x409)
    font.flavor = flavor
    path.parent.mkdir(parents=True, exist_ok=True)
    font.save(path)


def assert_no_reserved_name(package):
    # An OFL Reserved Font Name may not stay on a modified font; rename it
    # inside the subset (name IDs 1, 3, 4, 6) before shipping if this trips.
    license_text = (NODE / package / "LICENSE_FONT").read_text()
    assert "with Reserved Font Name" not in license_text, f"{package} reserves its name"
    return license_text


def used_icon_names(glyphmap):
    names = set()
    for path in (ROOT / "src").rglob("*.ts*"):
        if ".test." not in path.name:
            names.update(re.findall(r"""['"]([a-z0-9-]+)['"]""", path.read_text()))
    return sorted(names & glyphmap.keys())


def main():
    faces, preloads = [], []
    for family, (source, stem, extra) in FONTS.items():
        license_text = assert_no_reserved_name("/".join(source.split("/")[:2]))
        source = NODE / source
        features = DEFAULT_FEATURES + extra
        everything = set(TTFont(source).getBestCmap())
        write(source, everything, features, NATIVE_OUT / f"{stem}.ttf", license_text)
        write(source, everything, features, WEB_OUT / f"{stem}.woff2", license_text, "woff2")
        faces.append(
            f'@font-face{{font-family:"{family}";src:url("/fonts/{stem}.woff2") format("woff2")}}'
        )
        preloads.append(f"/fonts/{stem}.woff2")

    glyphmap = json.loads((NODE / IONICONS / "glyphmaps/Ionicons.json").read_text())
    icons = used_icon_names(glyphmap)
    write(NODE / IONICONS / "fonts/Ionicons.ttf", [glyphmap[n] for n in icons], [], WEB_OUT / "ionicons.woff2", (NODE / IONICONS / "LICENSE").read_text(), "woff2")
    faces.append('@font-face{font-family:"Ionicons";src:url("/fonts/ionicons.woff2") format("woff2")}')
    preloads.append("/fonts/ionicons.woff2")
    ICON_NAMES.write_text(json.dumps(icons, indent=2) + "\n")

    WEB_FACES.write_text(
        "// Generated by scripts/subset-fonts.py. Do not edit.\n"
        f"export const fontFaceCss = {json.dumps(''.join(faces))};\n"
        f"export const preloadedFonts = {json.dumps(preloads, indent=2)};\n"
    )
    for path in sorted([*NATIVE_OUT.glob("*.ttf"), *WEB_OUT.glob("*.woff2")]):
        print(f"{path.stat().st_size:>8}  {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
